#!/usr/bin/env python3
"""Generate the presets format-check cases in spec/fixtures/presets_load/ (spec/README.md "Loading presets").

Both apps run `cases.json` in unit tests (Android `PresetLoadCasesTest`, iOS `PresetLoadCasesTests`): every case must
load ("ok") or be refused for the stated reason. The output is deterministic, so re-running must produce no diff; CI
and build_all.sh run it with --check. Presets are not signed (user decision 2026-10-20): the apps only check the format.

Checks both apps implement (PresetBundleLoader), with the failure reason names used by the `sync_failure_reason`
analytics enum:
  1. header      : a JSON object with integer schema_version and presets_version   -> parse
  2. schema gate : schema_version <= 2 (the supported version)                     -> bad_schema
  3. monotonic   : presets_version > the installed version (0 = none installed)    -> stale_version
  4. full decode : the whole bundle decodes into the model                         -> parse
`check()` below is the Python reference for these steps (step 4 = every exam valid against the exam schema).
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import SPEC, require  # noqa: E402

OUT = os.path.join(SPEC, "fixtures", "presets_load")
SUPPORTED_SCHEMA_VERSION = 2
FAILURE_REASONS = ["bad_schema", "stale_version", "parse"]


def canonical(obj) -> bytes:
    """Same serialisation as build_presets.py, so the cases exercise the real byte layout."""
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode()


def sample_bundle(version=7, schema=2):
    return {
        "schema_version": schema,
        "presets_version": version,
        "generated_on": "2026-01-01",
        "disclaimer": "Test case. Not real exam data.",
        "exams": [{
            "id": "test_exam", "name": "Test Exam", "body": "TEST", "category": "banking", "portal": None,
            "live_photo_capture": False, "status": "active",
            "documents": [{
                "type": "photo", "required": True, "formats": ["jpg", "jpeg"],
                "size_kb": {"min": 20, "max": 50, "target": 38},
                "dimensions": {"mode": "preferred", "width": 200, "height": 230},
            }],
            "special_rules": [],
            "sources": [{"url": "https://example.com/notice.pdf", "kind": "official"}],
            "confidence": "high", "confidence_note": "Test case", "last_verified": "2026-01-01",
        }],
    }


def build():
    """Return {filename: bytes} for every case file."""
    files = {
        "sample_presets.json": canonical(sample_bundle()),
        "schema3_presets.json": canonical(sample_bundle(version=9, schema=3)),
        "malformed_presets.json": b'{"schema_version":2,"presets_version":8,"exams":[{"id":',
        "bad_shape_presets.json": canonical({"schema_version": 2, "presets_version": 8, "exams": "not-a-list"}),
        "not_an_object.json": b"[1,2,3]",
        "empty.json": b"",
    }
    load = [  # current_version = what is installed; expect = "ok" or a failure reason
        ("newer_version_accepted", "sample_presets.json", 6, "ok"),
        ("first_install_accepted", "sample_presets.json", 0, "ok"),
        ("same_version_rejected", "sample_presets.json", 7, "stale_version"),
        ("older_version_rejected", "sample_presets.json", 9, "stale_version"),
        ("unsupported_schema_rejected", "schema3_presets.json", 0, "bad_schema"),
        ("garbage_rejected", "malformed_presets.json", 0, "parse"),
        ("wrong_shape_rejected", "bad_shape_presets.json", 0, "parse"),
        ("not_an_object_rejected", "not_an_object.json", 0, "parse"),
        ("empty_file_rejected", "empty.json", 0, "parse"),
    ]
    cases = {
        "_doc": "Run by Android (:core:presets) and iOS (Presets) unit tests. Files are in this directory. Each case "
                "must load (ok) or be refused for the stated reason. Generated by spec/tools/make_presets_load_cases.py.",
        "supported_schema_version": SUPPORTED_SCHEMA_VERSION,
        "supported_failure_reasons": FAILURE_REASONS,
        "load_cases": [{"id": i, "bundle": b, "current_version": c, "expect": e} for i, b, c, e in load],
    }
    files["cases.json"] = (json.dumps(cases, indent=2, ensure_ascii=False) + "\n").encode()
    return files


def check(raw: bytes, current_version: int) -> str:
    """The Python reference for the apps' format checks: "ok" or the failure reason."""
    try:
        bundle = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError):
        return "parse"
    if not isinstance(bundle, dict):
        return "parse"
    schema, version = bundle.get("schema_version"), bundle.get("presets_version")
    if not all(isinstance(v, int) and not isinstance(v, bool) for v in (schema, version)):
        return "parse"
    if schema > SUPPORTED_SCHEMA_VERSION:
        return "bad_schema"
    if version <= current_version:
        return "stale_version"
    exams = bundle.get("exams")
    if not isinstance(exams, list):
        return "parse"
    require("jsonschema")
    import jsonschema
    with open(os.path.join(SPEC, "schema", "exam.schema.json"), encoding="utf-8") as f:
        validator = jsonschema.Draft202012Validator(json.load(f))
    return "ok" if all(isinstance(e, dict) and validator.is_valid(e) for e in exams) else "parse"


def drift(files=None):
    """Paths (relative to the repo) whose content differs from what build() makes."""
    files = files or build()
    stale = []
    for name, data in files.items():
        path = os.path.join(OUT, name)
        current = open(path, "rb").read() if os.path.exists(path) else None
        if current != data:
            stale.append(os.path.relpath(path, os.path.dirname(SPEC)))
    return stale


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the files on disk are out of date")
    args = ap.parse_args()
    files = build()
    stale = drift(files)
    if args.check:
        if stale:
            print("✗ presets load cases are stale (run spec/tools/make_presets_load_cases.py):", *stale,
                  sep="\n    ", file=sys.stderr)
            sys.exit(1)
        print("✓ presets load cases up to date")
        return
    os.makedirs(OUT, exist_ok=True)
    for name, data in files.items():
        with open(os.path.join(OUT, name), "wb") as f:
            f.write(data)
    print(f"✓ presets load cases written ({len(stale)} changed)")


if __name__ == "__main__":
    main()
